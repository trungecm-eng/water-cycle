import assert from 'node:assert/strict';
import { launchBrowser, baseUrl, trackErrors } from './browser.mjs';
const browser = await launchBrowser();
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = trackErrors(page);
  await page.goto(`${baseUrl}/?quality=low&speed=8&paused=1&sun=0&wind=100`);
  await page.waitForFunction(() => window.__sim?.scene);
  const before = await page.evaluate(() => window.__sim);
  assert.equal(await page.locator('.control-icon').count(), 2);
  assert.match(await page.locator('#sun-ends').innerText(), /Tắt nắng.*Nắng gắt/s);
  assert.match(await page.locator('#wind-ends').innerText(), /Lặng gió.*Gió mạnh/s);
  await page.locator('[data-speed="2"]').click();
  await page.locator('#default-controls').click();
  const after = await page.evaluate(() => window.__sim);
  assert.equal(after.sun, 50);
  assert.equal(after.wind, 40);
  assert.equal(after.time, before.time);
  assert.deepEqual(after.particles, before.particles);
  assert.deepEqual(after.rainTally, before.rainTally);
  assert.deepEqual(after.camera, before.camera);
  assert.equal(after.speed, 2);
  assert.equal(after.paused, true);
  assert.equal(await page.locator('#sun-value').textContent(), '50');
  assert.equal(await page.locator('#wind').inputValue(), '40');
  assert.equal(await page.locator('[data-speed][aria-pressed="true"]').count(), 1);
  await page.locator('#wind').fill('75');
  await page.locator('#wind').dispatchEvent('input');
  assert.equal(await page.evaluate(() => window.__sim.wind), 75);
  assert.equal(await page.locator('#wind-value').textContent(), '75');
  await page.locator('#default-controls').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => window.__sim.wind), 40);
  await page.locator('#toggle-labels').click();
  await page.waitForFunction(() => window.__sim.scene.labels.every(label => !label.visible));
  await page.keyboard.press('l');
  assert.equal(await page.locator('#toggle-labels').getAttribute('aria-pressed'), 'true');
  // Global shortcuts work on buttons; Space must toggle pause exactly once.
  await page.locator('#default-controls').focus();
  await page.keyboard.press('Space');
  assert.equal(await page.evaluate(() => window.__sim.paused), false);
  await page.keyboard.press('Space');
  assert.equal(await page.evaluate(() => window.__sim.paused), true);
  await page.keyboard.press('4');
  assert.equal(await page.evaluate(() => window.__sim.speed), 4);
  await page.locator('#sun').focus();
  await page.keyboard.press('Space');
  await page.keyboard.press('1');
  await page.keyboard.press('l');
  assert.equal(await page.evaluate(() => window.__sim.paused), true);
  assert.equal(await page.evaluate(() => window.__sim.speed), 4);
  assert.equal(await page.locator('#toggle-labels').getAttribute('aria-pressed'), 'true');
  await page.locator('#default-controls').focus();
  await page.keyboard.press('r');
  assert.equal(await page.evaluate(() => window.__sim.speed), 1);
  assert.deepEqual(errors, []);
  console.log('Slider defaults preserve simulation; speed, labels and keyboard controls passed.');
} finally { await browser.close(); }
